def can_build(env, platform):
    env.module_add_dependencies("grit", ["gdscript"])
    # Grit only exists where it is used: the editor (toolbar, build profile, export
    # plugin) and compiled templates, which are built with grit_generated set to the
    # project's generated sources. A plain export template must stay stock Godot so
    # that a VM export carries no Grit code at all.
    return env.editor_build or bool(env["grit_generated"])


def configure(env):
    pass


def get_opts(platform):
    from SCons.Variables import BoolVariable, PathVariable

    return [
        BoolVariable(
            "grit_conformance",
            "Always activate generated code, used to run the GDScript test suite natively",
            False,
        ),
        PathVariable(
            "grit_generated",
            "Directory containing the C++ sources generated by Grit",
            "",
            PathVariable.PathAccept,
        ),
    ]
